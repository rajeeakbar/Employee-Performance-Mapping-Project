-- Q14
DELIMITER $$

CREATE FUNCTION ValidateRole
(
exp_years INT
)

RETURNS VARCHAR(50)

DETERMINISTIC

BEGIN

RETURN

CASE

WHEN exp_years <= 2
THEN 'JUNIOR DATA SCIENTIST'

WHEN exp_years > 2
AND exp_years <= 5
THEN 'ASSOCIATE DATA SCIENTIST'

WHEN exp_years > 5
AND exp_years <= 10
THEN 'SENIOR DATA SCIENTIST'

WHEN exp_years > 10
AND exp_years <= 12
THEN 'LEAD DATA SCIENTIST'

WHEN exp_years > 12
AND exp_years <= 16
THEN 'MANAGER'

ELSE 'INVALID ROLE'

END;

END $$

DELIMITER ;

SELECT

EMP_ID,

FIRST_NAME,

ROLE AS CURRENT_ROLE,

ValidateRole(EXP)
AS STANDARD_ROLE

FROM data_science_team;

